package runner

// Coverage of re-executions of a test binary (granularity: func recording). The
// helper-process pattern runs part of a test in a child: exec.Command(os.Args[0],
// "-test.run=^TestCrasher$") with a variable telling the child what to do. The child is
// the same coverage binary, but a test binary writes its counters only where
// -test.gocoverdir says (without it, to a temporary directory it removes), and the
// child's arguments are the test's. So the binary gets one more test file, added
// through -overlay, whose init sets the -test.gocoverdir flag to $SMATES_GOCOVERDIR
// (registering the testing flags early; os.Args is left alone, since a child may be a
// command parsing its own arguments); runFunc sets that variable to the function's coverage directory. The
// function's process and every re-execution that inherits its environment then write
// their counters there, and the function's profile, which go merges from everything in
// that directory when its tests end, counts what the children executed.
//
// A test binary writes its counters when its tests end. A child that does not get there
// (it panics, calls os.Exit as the classic TestHelperProcess does, or is killed) writes
// none, and what it executed is unknown. The init therefore also leaves a marker named
// after its process ID; a marker without a counter file of that process makes the
// function's coverage uncertain, as a missing profile does (every Go file of its static
// closure becomes a content dependency).
//
// The same file gives re-executions a test log of their own (recording at either
// granularity: package recording adds it to every package it runs). A test log is per
// process (-test.testlogfile, which the child's arguments lack), so what a child read
// would not be seen: with $SMATES_GOTESTLOGDIR set and no -test.testlogfile on its
// command line (the process smates started has one), a process run as a test binary
// (no arguments, or a -test. flag first) points the flag at <dir>/<pid>.testlog and
// writes its working directory to <dir>/<pid>.test; one run with arguments of its own
// (a TestMain dispatching to the program's command line, an -exec wrapper) only writes
// its directory to <dir>/<pid>.cmd. trace.GoTestLogs adds what the children read, or
// may have read, to the test's dependencies.

import (
	"encoding/json"
	"fmt"
	"go/build"
	"os"
	"path/filepath"
	"strings"

	"github.com/dotneet/smates/internal/trace"
)

// childMarkerPrefix starts the name of the marker a process of the binary leaves in
// the coverage directory when it starts (followed by its process ID).
const childMarkerPrefix = "smates-started."

// childCoverEnv names the coverage directory of the test function being recorded.
const childCoverEnv = trace.GoChildCoverEnv

// childSource is the test file that makes the binary of package name use
// $SMATES_GOCOVERDIR as -test.gocoverdir and leave a start marker there, and gives a
// re-execution a test log in $SMATES_GOTESTLOGDIR. It only adds an init function (and
// file-scoped imports), so it cannot clash with the package's declarations. It runs
// before testing parses the flags: testing.Init registers them (MainStart calling it
// again changes nothing) and the values set stay the defaults flags on the command line
// override. The arguments are only read: a re-execution may run the program's own
// command line (a TestMain dispatching on an environment variable to a CLI that rejects
// unknown flags).
func childSource(name string) string {
	return `// Code generated by smates (tracing of re-executions of this test binary). DO NOT EDIT.

package ` + name + `

import (
	smatesflag "flag"
	smatesos "os"
	smatesstrconv "strconv"
	smatesstrings "strings"
	smatestesting "testing"
)

func init() {
	pid := smatesstrconv.Itoa(smatesos.Getpid())
	if d := smatesos.Getenv("` + childCoverEnv + `"); d != "" {
		smatestesting.Init()
		smatesflag.Set("test.gocoverdir", d)
		smatesos.WriteFile(d+"/` + childMarkerPrefix + `"+pid, nil, 0o644)
	}
	if d := smatesos.Getenv("` + trace.GoChildLogEnv + `"); d != "" {
		for _, a := range smatesos.Args[1:] {
			if f, _, _ := smatesstrings.Cut(smatesstrings.TrimLeft(a, "-"), "="); f == "test.testlogfile" {
				return // the process smates started (or one given a log of its own)
			}
		}
		wd, err := smatesos.Getwd()
		if err != nil {
			return
		}
		if len(smatesos.Args) > 1 && !smatesstrings.HasPrefix(smatesos.Args[1], "-test.") && !smatesstrings.HasPrefix(smatesos.Args[1], "--test.") {
			// Not run as a test binary (a TestMain dispatching to the program's own
			// command line, an -exec wrapper): it only says where it ran.
			smatesos.WriteFile(d+"/"+pid+".` + trace.GoChildCmdSuffix + `", []byte(wd), 0o644)
			return
		}
		smatestesting.Init()
		smatesos.WriteFile(d+"/"+pid+".` + trace.GoChildTestSuffix + `", []byte(wd), 0o644)
		smatesflag.Set("test.testlogfile", d+"/"+pid+".testlog")
	}
}
`
}

// childrenCovered reports whether every process of the binary that left a start marker
// in coverage directory dir also wrote its counters there (files
// covcounters.<meta hash>.<pid>.<time>).
func childrenCovered(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	started, wrote := map[string]bool{}, map[string]bool{}
	for _, e := range entries {
		name := e.Name()
		if pid, ok := strings.CutPrefix(name, childMarkerPrefix); ok {
			started[pid] = true
		} else if f := strings.Split(name, "."); len(f) == 4 && f[0] == "covcounters" {
			wrote[f[2]] = true
		}
	}
	for pid := range started {
		if !wrote[pid] {
			return false
		}
	}
	return true
}

// childCoverFlags is childFlags for the package in pkgDir (package clause name).
func childCoverFlags(build []string, goflags, goDir, pkgDir, name, work string) ([]string, error) {
	if name == "" {
		return build, nil
	}
	return childFlags(build, goflags, goDir, map[string]string{pkgDir: name}, work)
}

// childFlags returns the build flags build, of a go command run in goDir with GOFLAGS
// goflags, with an -overlay adding the child test file (childSource) to the packages in
// the directories of pkgs (to their package clause names), written to work. The user's
// own -overlay (the last one of the command, else of GOFLAGS: the command line wins) is
// merged into it, since ours on the command line replaces it. Without packages, or with
// an overlay that cannot be read (go reports it), the flags are returned as they are.
func childFlags(build []string, goflags, goDir string, pkgs map[string]string, work string) ([]string, error) {
	if len(pkgs) == 0 {
		return build, nil
	}
	user := ""
	for _, w := range strings.Fields(goflags) {
		if flag, val, _ := strings.Cut(strings.TrimLeft(w, "-"), "="); flag == "overlay" && strings.HasPrefix(w, "-") {
			user = val
		}
	}
	var out []string // build without its -overlay flags
	for i := 0; i < len(build); i++ {
		flag, val, hasVal := strings.Cut(strings.TrimLeft(build[i], "-"), "=")
		if flag != "overlay" || !strings.HasPrefix(build[i], "-") {
			out = append(out, build[i])
			continue
		}
		if !hasVal && i+1 < len(build) {
			i++
			val = build[i]
		}
		user = val
	}
	replace := map[string]string{}
	if user != "" {
		data, err := os.ReadFile(absFrom(goDir, user))
		if err != nil {
			return build, nil
		}
		var ov struct{ Replace map[string]string }
		if err := json.Unmarshal(data, &ov); err != nil {
			return build, nil
		}
		// Relative paths in an overlay are relative to the go command's directory.
		for k, v := range ov.Replace {
			replace[absFrom(goDir, k)] = absFrom(goDir, v)
		}
	}
	for pkgDir, name := range pkgs {
		file := ""
		for n := 0; file == ""; n++ {
			f := filepath.Join(pkgDir, fmt.Sprintf("zz_smates_cover%s_test.go", suffixN(n)))
			if _, taken := replace[f]; !taken && !exists(f) {
				file = f
			}
		}
		src := filepath.Join(work, "smates_"+name+"_test.go")
		if err := os.WriteFile(src, []byte(childSource(name)), 0o644); err != nil {
			return nil, err
		}
		replace[file] = src
	}
	data, err := json.Marshal(map[string]any{"Replace": replace})
	if err != nil {
		return nil, err
	}
	overlay := filepath.Join(work, "overlay.json")
	if err := os.WriteFile(overlay, data, 0o644); err != nil {
		return nil, err
	}
	return append(out, "-overlay="+overlay), nil
}

// childGoFlags returns the GOFLAGS words goflags of package recording with an -overlay
// adding the child test file to the packages of units (repo-relative package
// directories), so that re-executions of their test binaries keep test logs of their
// own. A package's name comes from go/build's default context; a package it cannot name
// (files of several packages) or in which it finds no test file (build tags) gets no
// file, which leaves what its re-executions read unknown. GOFLAGS is split on spaces: below a trace directory with spaces, nothing is added.
func childGoFlags(rc *RunContext, goflags, units []string) ([]string, error) {
	work := filepath.Join(rc.TraceDir, "go-overlay")
	if strings.ContainsAny(work, " \t") {
		return goflags, nil
	}
	pkgs := map[string]string{}
	bctx := goBuildContext(rc)
	for _, u := range units {
		dir := filepath.Join(rc.Repo.Root, filepath.FromSlash(u))
		// Only packages with tests: go test runs no binary for the others.
		if p, err := bctx.ImportDir(dir, 0); err == nil && p.Name != "" && len(p.TestGoFiles)+len(p.XTestGoFiles) > 0 {
			pkgs[dir] = p.Name
		}
	}
	if len(pkgs) == 0 {
		return goflags, nil
	}
	if err := os.MkdirAll(work, 0o755); err != nil {
		return nil, err
	}
	return childFlags(goflags, "", rc.Dir(), pkgs, work)
}

// goBuildContext is go/build's default context with the suite's GOOS, GOARCH and
// CGO_ENABLED and the -tags of GOFLAGS, the suite command and the arguments passed
// through (the last one wins, as with go test).
func goBuildContext(rc *RunContext) build.Context {
	bctx := build.Default
	env := suiteEnv(rc.Suite)
	if v := Getenv(env, "GOOS"); v != "" {
		bctx.GOOS = v
	}
	if v := Getenv(env, "GOARCH"); v != "" {
		bctx.GOARCH = v
	}
	if v := Getenv(env, "CGO_ENABLED"); v != "" {
		bctx.CgoEnabled = v == "1"
	}
	for _, f := range goListFlags(rc) {
		if tags, ok := strings.CutPrefix(f, "-tags="); ok {
			bctx.BuildTags = strings.FieldsFunc(tags, func(r rune) bool { return r == ',' || r == ' ' })
		}
	}
	return bctx
}

func suffixN(n int) string {
	if n == 0 {
		return ""
	}
	return fmt.Sprint(n)
}

// absFrom makes p absolute relative to dir.
func absFrom(dir, p string) string {
	if p == "" || filepath.IsAbs(p) {
		return p
	}
	return filepath.Join(dir, p)
}
